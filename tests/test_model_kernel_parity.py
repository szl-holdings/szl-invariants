from __future__ import annotations

import ast
import importlib.util
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
KERNEL_SOURCE = ROOT / "torch-ext" / "szl_invariants" / "__init__.py"
KERNEL_METADATA = ROOT / "torch-ext" / "szl_invariants" / "metadata.json"
VARIANTS = ("torch-cpu", "torch-universal")


def _source(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def _publisher():
    loaded = sys.modules.get("szl_kernel_publish")
    if loaded is not None:
        return loaded
    spec = importlib.util.spec_from_file_location(
        "szl_kernel_publish", ROOT / "scripts" / "szl_kernel_publish.py"
    )
    module = importlib.util.module_from_spec(spec)
    sys.modules["szl_kernel_publish"] = module
    spec.loader.exec_module(module)
    return module


def _literal_assignment(tree: ast.Module, name: str):
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id == name
        ):
            return ast.literal_eval(node.value)
    raise AssertionError(f"missing top-level assignment: {name}")


def test_every_hub_variant_is_the_kernel_source_after_line_normalization() -> None:
    """Both Hub variants are built from torch-ext/ only; there is no second copy to drift."""
    kp = _publisher()
    cfg = kp.find_kernel(ROOT, "SZLHOLDINGS/szl-invariants")
    commit = kp.resolve_commit(ROOT, "HEAD")
    payload = kp.build_payload(cfg, ROOT, commit)
    head_source = kp.read_tree_files(ROOT, commit, "torch-ext/szl_invariants")
    for variant in VARIANTS:
        prefix = f"build/{variant}/szl_invariants/"
        built = {path[len(prefix):]: data for path, data in payload.items() if path.startswith(prefix)}
        assert built == {rel: data.replace(b"\r\n", b"\n") for rel, data in head_source.items()}
    tracked = kp.git(ROOT, "ls-files", "--", "build").decode().split()
    assert tracked == [], "the Hub build/ is generated by hf-kernel-publish, never committed"


def test_quarantined_surrogate_disclosure_is_present() -> None:
    source = _source(KERNEL_SOURCE)
    tree = ast.parse(source, filename=str(KERNEL_SOURCE))
    docstring = ast.get_docstring(tree, clean=False) or ""
    provenance = _literal_assignment(tree, "PROVENANCE")

    assert "ships no\ntrained weights" in docstring
    assert "QUARANTINED" in docstring
    assert "ALSO ships a REAL trained companion model" not in docstring
    assert 'revision="main"' not in docstring
    assert provenance["trained_weights_present"] is False
    assert "model.joblib" in provenance["trained_weights_role"]
    assert "QUARANTINED" in provenance["trained_weights_role"]


def test_metadata_rejects_trained_weight_presence() -> None:
    metadata = json.loads(KERNEL_METADATA.read_text(encoding="utf-8"))

    assert metadata["artifact_kind"] == "kernel-code-and-configuration"
    assert metadata["trained_weights_present"] is False
    assert metadata["stdlib_without_signature_verification"] is True
    assert metadata["stdlib_only"] is False
    assert metadata["optional_dependencies"]["signature_verification"] == "cryptography>=46,<50"
